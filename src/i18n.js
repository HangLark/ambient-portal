export function detectLanguage(storage, languages = ['en-US']) {
  try {
    const saved = storage?.getItem('ambient-portal.language');
    if (Object.hasOwn(dictionaries, saved)) return saved;
  } catch { /* Storage may be unavailable in private or restricted contexts. */ }
  return languages[0]?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US';
}

export function saveLanguage(storage, language) {
  try { storage?.setItem('ambient-portal.language', language); } catch { /* Session-only preference. */ }
}

export function translate(language, key) {
  return dictionaries[language]?.[key] ?? dictionaries['en-US'][key] ?? key;
}
